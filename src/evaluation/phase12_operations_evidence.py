"""Immutable operational packages and network-free full-cohort verification."""
from pathlib import Path
from src.evaluation import phase12_prospective as p
from src.evaluation import phase12_evidence as evidence
from src.evaluation import phase12_operations as op


def certify_tests(path, focused, protected, full):
    """Index exact test evidence; reject errors and any newly failing test."""
    reference = p.run_path(path) / 'reports/report-001/tests/full.xml'
    refs = {name: p.identity(Path(file).resolve()) for name, file in
            [('focused', focused), ('protected', protected), ('full', full), ('inherited', reference)]}
    summaries = {name: p.evidence11.test_summary(p.frozen.reference(ref)) for name, ref in refs.items()}
    p.check(all(s['cases'] > 0 for s in summaries.values()), 'EMPTY_TEST_REPORT')
    new = sorted(set(summaries['full']['failures']) - set(summaries['inherited']['failures']))
    p.check(not new and not summaries['focused']['failures'] and not summaries['protected']['failures'],
            'NEW_OPERATIONAL_TEST_FAILURE')
    row = p.seal({'sources': refs, 'summaries': summaries, 'new_unexplained_failures': new})
    return op.put(op.root(path) / 'test_evidence.json', row)


def check_tests(row):
    p.frozen.sealed(row, 'record_sha256')
    actual = {name: p.evidence11.test_summary(p.frozen.reference(ref)) for name, ref in row['sources'].items()}
    p.check(actual == row['summaries'], 'OPERATION_TEST_REPORT_MISMATCH')
    p.check(not (set(actual['full']['failures']) - set(actual['inherited']['failures'])) and
            not actual['focused']['failures'] and not actual['protected']['failures'] and
            not row['new_unexplained_failures'], 'NEW_OPERATIONAL_TEST_FAILURE')


def seal_report(path, directory, outcomes, preserved):
    # Outcome files are restart points. Every value below derives from immutable
    # inputs, so a crash during report writing can complete the same publication.
    lines = ['# Phase 12 operational checkpoint', '',
        '| League | Previous pairs/settled | Pairs | New pairs | New settled | Pending | Replay | Scientific state | Authorization |',
        '|---|---|---|---|---|---|---|---|---|']
    for row in outcomes:
        league = row['league']
        if 'checkpoint' not in row:
            lines.append(f"| {league} | unknown | — | — | — | — | FAILED | {row['scientific_state']} | NOT AUTHORIZED |")
            continue
        checkpoint = row['checkpoint']
        before = row['before']
        lines.append(f"| {league} | {before['pairs']}/{before['settled']} | {checkpoint['pairs']} | {row['newly_admitted']} | {row['newly_settled']} | {checkpoint['pending']} | {checkpoint['replay']} | {checkpoint['scientific_state']} | {row['authorization']['state']} |")
        members = sorted((p.run_path(path) / league / 'journal').glob('*.json'))[:checkpoint['journal_count']]
        op.put(directory / league / 'cohort_index.json', {
            'league': league, 'prefix': p.specification(path)['leagues'][league]['prefix'],
            'ordered_journal': [p.identity(file) for file in members],
            'ordered_pairs': checkpoint['cohort_pair_hashes'],
            'ordered_settlements': checkpoint['cohort_settlement_hashes']})
    lines += ['', 'Scientific readiness and deployment authorization remain separate. No activation, model change, calibration or retrospective prediction is performed.',
        '', 'Full metric/reliability, horizon, identity and incident evidence is in each league outcome.json. An independent verification receipt binds this report after network-free cohort replay.']
    # Text is stored in an atomic JSON envelope, with a human-readable Markdown view
    # generated by the CLI on stdout. No replace-in-place report operation exists.
    op.put(directory / 'readable_report.json', {'markdown': '\n'.join(lines) + '\n'})
    preserved = op.integrity(path)
    op.put(directory / 'protected_hash_comparison.json', preserved)
    test_file = op.root(path) / 'test_evidence.json'
    tests = p.identity(test_file) if test_file.exists() else None
    if tests:
        check_tests(p.read(test_file))
    files = set()
    for base in (p.run_path(path),):
        files.update(file for file in base.rglob('*') if file.is_file() and file.suffix not in ('.lock', '.tmp')
                     and file != directory / 'report.json')
    # Include failed and partial retrievals as well as qualified source trees.
    for base in (p.ROOT / 'baselines/phase11').glob('phase12-acquisition-*'):
        files.update(file for file in base.rglob('*') if file.is_file() and file.suffix not in ('.lock', '.tmp'))
    report = p.seal({'schema': 'ffps.phase12_operational_report.v1',
        'intent': p.identity(directory / 'intent.json'), 'leagues': outcomes,
        'protected_integrity': preserved, 'tests': tests,
        'degraded': any('checkpoint' not in r or r.get('error') or
                        r['checkpoint']['scientific_state'] in ('DATA_SOURCE_TEMPORARILY_BLOCKED', 'PROTOCOL_VIOLATION_BLOCKED') for r in outcomes),
        'artifacts': [p.identity(file) for file in sorted(files)], 'promotion_performed': False})
    op.put(directory / 'report.json', report)
    return {'duplicate': False, 'report': p.identity(directory / 'report.json'), 'degraded': report['degraded']}


def verify(path):
    with p.state_lock(op.root(path) / 'runner.lock'):
        preserved = op.integrity(path)
        spec = p.specification(path)
        contexts = {}
        for league in p.source.LEAGUES:
            print('Offline replay: ' + league, flush=True)
            contexts[league] = p.load_cohort(path, league)
            for file in (p.run_path(path) / league / 'checkpoints').glob('*.json'):
                evidence.verify_checkpoint(p.read(file), contexts[league], len(spec['leagues'][league]['prefix']))
        # Preserve the original sealed implementation and all source bytes in its
        # package; current journals above are independently replayed in full.
        for directory in (p.run_path(path) / 'reports').glob('report-*'):
            index = p.read(directory / 'artifact_index.json')
            p.frozen.sealed(index, 'record_sha256')
            for ref in index['artifacts'] + index['implementation_sources']:
                p.frozen.reference(ref)
        previous, keys = None, set()
        directories = op.reports(path)
        p.check(bool(directories), 'NO_OPERATIONAL_REPORT')
        # Prior successful receipts also anchor the tail against report deletion.
        for receipt_file in (op.root(path) / 'verifications').glob('*.json'):
            receipt = p.read(receipt_file)
            p.frozen.sealed(receipt, 'record_sha256')
            p.frozen.reference(receipt['report'])
        for directory in directories:
            report = p.read(directory / 'report.json')
            p.frozen.sealed(report, 'record_sha256')
            intent = p.read(p.frozen.reference(report['intent']))
            p.frozen.sealed(intent, 'record_sha256')
            p.check(intent['previous_report'] == previous and intent['key'] not in keys, 'OPERATION_CHAIN_MISMATCH')
            keys.add(intent['key'])
            for ref in report['artifacts']:
                p.frozen.reference(ref)
            expected = {ref['path'] for ref in report['artifacts'] if (p.ROOT / ref['path']).is_relative_to(directory)}
            actual = {file.relative_to(p.ROOT).as_posix() for file in directory.rglob('*')
                      if file.is_file() and file.name != 'report.json' and file.suffix != '.tmp'}
            p.check(expected == actual, 'OPERATION_REPORT_INVENTORY_MISMATCH')
            p.check([r['league'] for r in report['leagues']] == list(p.source.LEAGUES), 'OPERATION_LEAGUE_INVENTORY_MISMATCH')
            for row in report['leagues']:
                p.frozen.sealed(row, 'record_sha256')
                league = row['league']
                p.check(row == p.read(directory / league / 'outcome.json'), 'OPERATION_OUTCOME_MISMATCH')
                p.check('checkpoint' in row, 'OPERATION_REPLAY_UNVERIFIED:' + league)
                checkpoint = row['checkpoint']
                ctx = contexts[league]
                evidence.verify_checkpoint(checkpoint, ctx, len(spec['leagues'][league]['prefix']))
                before = row['before']
                p.check(before == p.read(directory / league / 'claim.json'), 'OPERATION_CLAIM_MISMATCH')
                events = ctx[-1]
                n = before['journal_count']
                p.check(n <= checkpoint['journal_count'] and (not n or events[n-1]['record_sha256'] == before['journal_head']), 'OPERATION_START_HEAD_MISMATCH')
                prefix_count = len(spec['leagues'][league]['prefix'])
                p.check(before['pairs'] == prefix_count + sum(e['kind'] == 'pair' for e in events[:n]) and
                        before['settled'] == sum(e['kind'] == 'settlement' for e in events[:n]), 'OPERATION_PREVIOUS_COUNTS_MISMATCH')
                p.check(row['newly_admitted'] == checkpoint['pairs'] - before['pairs'] and
                        row['newly_settled'] == checkpoint['settled'] - before['settled'], 'OPERATION_COUNT_DELTA_MISMATCH')
                p.check(row['authorization'] == op.authorization(ctx[1]), 'AUTHORIZATION_STATE_MISMATCH')
                p.check(row['new_incidents'] == [e['payload'] for e in events[n:checkpoint['journal_count']]
                        if e['kind'] == 'incident'], 'OPERATION_INCIDENT_MISMATCH')
                cohort = p.read(directory / league / 'cohort_index.json')
                files = sorted((p.run_path(path) / league / 'journal').glob('*.json'))[:checkpoint['journal_count']]
                p.check(cohort == {'league': league, 'prefix': spec['leagues'][league]['prefix'],
                    'ordered_journal': [p.identity(f) for f in files], 'ordered_pairs': checkpoint['cohort_pair_hashes'],
                    'ordered_settlements': checkpoint['cohort_settlement_hashes']}, 'OPERATION_COHORT_INDEX_MISMATCH')
            if report['tests']:
                check_tests(p.read(p.frozen.reference(report['tests'])))
            p.check(not report['promotion_performed'], 'OPERATION_PROMOTION_FORBIDDEN')
            previous = p.identity(directory / 'report.json')
        result = p.seal({'verified': True, 'report': previous, 'protected_integrity': preserved,
            'leagues': [{'league': league, 'pairs': len(ctx[3]), 'settled': len(ctx[4]), 'replay': 'VERIFIED'}
                        for league, ctx in contexts.items()], 'promotion_performed': False})
        op.put(op.root(path) / 'verifications' / (result['record_sha256'] + '.json'), result)
        return result
